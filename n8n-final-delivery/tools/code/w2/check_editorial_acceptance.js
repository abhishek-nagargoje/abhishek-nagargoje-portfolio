// @mode each
// @lib common,article
// The article passes only if EVERY mandatory check passes: all evaluator
// checks, no unsupported claims and all deterministic checks below.
const ctx = $json.ctx;
const a = ctx.article;
const r = ctx.editorial_raw;
const kw = ctx.keyword.Primary_Keyword.toLowerCase();
const integ = ctx.article_integrity;
const body = plainFromMarkdown(a.Article_Markdown);
const firstWords = body.split(/\s+/).slice(0, 150).join(' ').toLowerCase();
// Natural keyword use: every significant keyword term (stems match, e.g.
// "service" / "services") instead of an exact phrase that invites stuffing.
const kwTokens = kw.split(/[^\p{L}\p{N}]+/u).filter((t) => t.length >= 3 && !['and', 'for', 'the', 'with', 'from', 'your'].includes(t));
function tokenShare(text) {
  if (!kwTokens.length) return 1;
  const hit = kwTokens.filter((t) => text.includes(t.length > 4 ? t.replace(/(es|s)$/, '') : t)).length;
  return hit / kwTokens.length;
}
const det = [
  { check: 'No unverified internal links', passed: integ.unverified_internal_links.length === 0, detail: integ.unverified_internal_links.join(', ') },
  { check: 'Brand facts reference retrieved knowledge only', passed: integ.unknown_fact_ids.length === 0, detail: integ.unknown_fact_ids.join(', ') },
  { check: 'External sources are well-formed https URLs', passed: integ.invalid_external_sources.length === 0, detail: integ.invalid_external_sources.join(', ') },
  { check: 'Primary keyword terms in H1 or title', passed: tokenShare((a.H1 + ' ' + a.Article_Title).toLowerCase()) === 1, detail: '' },
  { check: 'Primary keyword terms in opening 150 words', passed: tokenShare(firstWords) >= 0.6, detail: '' },
  { check: 'Meta description length 70-160', passed: a.Meta_Description.length >= 70 && a.Meta_Description.length <= 160, detail: String(a.Meta_Description.length) },
  { check: 'SEO title length <= 65', passed: a.SEO_Title.length <= 65, detail: String(a.SEO_Title.length) },
  { check: 'No ranking guarantees or AI-detection claims', passed: !/(guarantee[ds]?|assured)\s+(top|first|#?1|number one)?\s*(rank|ranking|position)|pass(es)?\s+ai[- ]detect|undetectable/i.test(body), detail: '' },
  { check: 'No absolute compliance guarantees', passed: !/100\s?%\s+(compliance|compliant|guarantee)|guaranteed\s+compliance/i.test(body), detail: '' },
];
const llmFailed = r.Individual_Checks.filter((x) => x.status !== 'PASS').map((x) => x.check + (x.notes ? ': ' + x.notes : ''));
const unsupported = (r.Unsupported_Claims || []).map((u) => (typeof u === 'string' ? { claim: u, reason: '', severity: 'major' } : {
  claim: truncate(u.claim, 500), reason: truncate(u.reason, 500), severity: asText(u.severity || 'major').toLowerCase() }));
const critical = unsupported.filter((u) => u.severity === 'critical' || /fabricat|invent|false|incorrect/i.test(u.reason));
const detFailed = det.filter((d) => !d.passed).map((d) => d.check + (d.detail ? ' (' + d.detail + ')' : ''));
const passed = r.Overall_Status === 'PASS' && llmFailed.length === 0 && unsupported.length === 0 && detFailed.length === 0;
const failed = [...new Set([...(r.Failed_Conditions || []).map(asText), ...llmFailed, ...detFailed])].filter(Boolean);
ctx.editorial = {
  attempt: ctx.attempt,
  overall_status: passed ? 'PASS' : (r.Overall_Status === 'REVIEW_REQUIRED' ? 'REVIEW_REQUIRED' : 'FAIL'),
  evaluator_status: r.Overall_Status,
  passed,
  critical_factual_failure: critical.length > 0,
  individual_checks: r.Individual_Checks,
  deterministic_checks: det,
  failed_conditions: failed,
  unsupported_claims: unsupported,
  required_corrections: (r.Required_Corrections || []).map((x) => truncate(x, 500)),
  reviewer_comments: r.Reviewer_Comments,
  disclaimer: 'Internal E-E-A-T-oriented editorial assessment generated by an AI evaluator; not a Google score or certification.',
};
delete ctx.editorial_raw;
return { json: { ctx } };
