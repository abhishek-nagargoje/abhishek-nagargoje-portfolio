function uuidFrom(...parts) {
  const h = crypto.createHash('sha1').update(parts.join('|')).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function readPromptSection(file) {
  const src = fs.readFileSync(path.join(ROOT, 'prompts', file), 'utf8');
  const m = src.match(/<!-- BEGIN SYSTEM INSTRUCTION -->\s*([\s\S]*?)\s*<!-- END SYSTEM INSTRUCTION -->/);
  if (!m) throw new Error(`No system instruction markers in prompts/${file}`);
  return m[1].trim();
}

function stripExports(src) {
  const i = src.indexOf('/* @exports */');
  return (i === -1 ? src : src.slice(0, i)).trimEnd();
}

// Reads a Code-node body, inlines "// @include a, b" libraries and replaces
// __PLACEHOLDER__ tokens with JSON literals.
function loadCode(rel, replacements) {
  let src = fs.readFileSync(path.join(CODE_DIR, rel), 'utf8');
  const inc = src.match(/^\/\/ @include ([\w, ]+)\n/);
  let prefix = '';
  if (inc) {
    src = src.slice(inc[0].length);
    const libs = inc[1].split(',').map((s) => s.trim()).filter(Boolean);
    prefix = libs
      .map((l) => `// ===== inlined from tools/code/lib/${l}.js =====\n` + stripExports(fs.readFileSync(path.join(CODE_DIR, 'lib', `${l}.js`), 'utf8')))
      .join('\n\n') + '\n\n// ===== node logic =====\n';
  }
  let out = prefix + src;
  for (const [token, value] of Object.entries(replacements || {})) {
    out = out.split(token).join(JSON.stringify(value));
  }
  const left = out.match(/__(?:PROMPT|SCHEMA|POLICY|CHECK)[A-Z0-9_]*__/g);
  if (left) throw new Error(`Unreplaced placeholder(s) in ${rel}: ${[...new Set(left)].join(', ')}`);
  return `// Generated by tools/build_workflows.js from tools/code/${rel} - edit the source file, then rebuild.\n` + out;
}

class Workflow {
  constructor(name) {
    this.name = name;
    this.nodes = [];
    this.connections = {};
  }

  add(node) {
    if (this.nodes.some((n) => n.name === node.name)) throw new Error(`Duplicate node name: ${node.name}`);
    node.id = uuidFrom(this.name, node.name);
    this.nodes.push(node);
    return node.name;
  }

  link(from, to, fromOutput = 0, toInput = 0) {
    if (!this.connections[from]) this.connections[from] = { main: [] };
    const main = this.connections[from].main;
    while (main.length <= fromOutput) main.push([]);
    main[fromOutput].push({ node: to, type: 'main', index: toInput });
  }

  chain(...names) {
    for (let i = 0; i < names.length - 1; i++) this.link(names[i], names[i + 1]);
  }

  toJSON(settings, extra) {
    for (const [from, c] of Object.entries(this.connections)) {
      if (!this.nodes.some((n) => n.name === from)) throw new Error(`Connection from unknown node ${from}`);
      for (const out of c.main) for (const t of out) if (!this.nodes.some((n) => n.name === t.node)) throw new Error(`Connection ${from} -> unknown node ${t.node}`);
    }
    return {
      name: this.name,
      nodes: this.nodes,
      connections: this.connections,
      active: false,
      settings,
      pinData: {},
      meta: { templateCredsSetupCompleted: false },
      tags: [],
      ...(extra || {}),
    };
  }
}

const P = (x, y) => [Math.round(x * 240), Math.round(y * 200)];

function code(name, pos, src, opts = {}) {
  return {
    name,
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position: pos,
    parameters: { mode: opts.perItem ? 'runOnceForEachItem' : 'runOnceForAllItems', jsCode: src },
    ...(opts.onError ? { onError: opts.onError } : {}),
    ...(opts.alwaysOutputData ? { alwaysOutputData: true } : {}),
  };
}

function pg(name, pos, query, params, opts = {}) {
  const parameters = { operation: 'executeQuery', query, options: {} };
  if (params && params.length) {
    parameters.options.queryReplacement = `={{ [${params.map((p) => `(${p}) ?? null`).join(', ')}] }}`;
  }
  return {
    name,
    type: 'n8n-nodes-base.postgres',
    typeVersion: 2.5,
    position: pos,
    parameters,
    credentials: CRED.postgres,
    ...(opts.onError ? { onError: opts.onError } : {}),
    ...(opts.alwaysOutputData ? { alwaysOutputData: true } : {}),
    ...(opts.executeOnce ? { executeOnce: true } : {}),
    ...(opts.retry ? { retryOnFail: true, maxTries: 3, waitBetweenTries: 3000 } : {}),
  };
}

function http(name, pos, p, opts = {}) {
  const parameters = { method: p.method || 'GET', url: p.url };
  if (p.auth === 'gemini') Object.assign(parameters, { authentication: 'genericCredentialType', genericAuthType: 'httpHeaderAuth' });
  if (p.auth === 'plagiarism') Object.assign(parameters, { authentication: 'genericCredentialType', genericAuthType: 'httpQueryAuth' });
  if (p.auth === 'docs') Object.assign(parameters, { authentication: 'predefinedCredentialType', nodeCredentialType: 'googleDocsOAuth2Api' });
  if (p.headers) parameters.sendHeaders = true, parameters.headerParameters = { parameters: Object.entries(p.headers).map(([n, v]) => ({ name: n, value: v })) };
  if (p.jsonBody) Object.assign(parameters, { sendBody: true, specifyBody: 'json', jsonBody: p.jsonBody });
  if (p.formBody) Object.assign(parameters, { sendBody: true, contentType: 'form-urlencoded', bodyParameters: { parameters: Object.entries(p.formBody).map(([n, v]) => ({ name: n, value: v })) } });
  const options = { timeout: p.timeout || 120000 };
  if (p.fullResponse || p.neverError || p.responseFormat) {
    options.response = { response: { ...(p.fullResponse ? { fullResponse: true } : {}), ...(p.neverError ? { neverError: true } : {}), ...(p.responseFormat ? { responseFormat: p.responseFormat } : {}) } };
  }
  if (p.batch) options.batching = { batch: { batchSize: p.batch[0], batchInterval: p.batch[1] } };
  if (p.redirects !== undefined) options.redirect = { redirect: { followRedirects: true, maxRedirects: p.redirects } };
  parameters.options = options;
  const credentials = p.auth === 'gemini' ? CRED.gemini : p.auth === 'plagiarism' ? CRED.plagiarism : p.auth === 'docs' ? CRED.docs : undefined;
  return {
    name,
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position: pos,
    parameters,
    ...(credentials ? { credentials } : {}),
    ...(opts.retry ? { retryOnFail: true, maxTries: opts.retry, waitBetweenTries: 5000 } : {}),
    ...(opts.onError ? { onError: opts.onError } : {}),
    ...(opts.executeOnce ? { executeOnce: true } : {}),
  };
}

let condCounter = 0;
function cond(wfName, leftValue, operator, rightValue) {
  condCounter += 1;
  const c = { id: uuidFrom(wfName, 'cond', String(condCounter), leftValue), leftValue, operator };
  if (rightValue !== undefined) c.rightValue = rightValue;
  return c;
}
const COND_OPTIONS = { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 };

function ifNode(wfName, name, pos, boolExpr) {
  return {
    name,
    type: 'n8n-nodes-base.if',
    typeVersion: 2.2,
    position: pos,
    parameters: {
      conditions: {
        options: COND_OPTIONS,
        conditions: [cond(wfName, `={{ ${boolExpr} }}`, { type: 'boolean', operation: 'true', singleValue: true })],
        combinator: 'and',
      },
      options: {},
    },
  };
}

// outputs: [{ key, equals }] compared against valueExpr (string). Fallback output is added last.
function switchNode(wfName, name, pos, valueExpr, outputs, fallbackName) {
  return {
    name,
    type: 'n8n-nodes-base.switch',
    typeVersion: 3.2,
    position: pos,
    parameters: {
      rules: {
        values: outputs.map((o) => ({
          conditions: {
            options: COND_OPTIONS,
            conditions: [cond(wfName, `={{ ${valueExpr} }}`, { type: 'string', operation: 'equals' }, o.equals)],
            combinator: 'and',
          },
          renameOutput: true,
          outputKey: o.key,
        })),
      },
      options: fallbackName ? { fallbackOutput: 'extra', renameFallbackOutput: fallbackName } : {},
    },
  };
}

function setTag(name, pos, assignments) {
  return {
    name,
    type: 'n8n-nodes-base.set',
    typeVersion: 3.4,
    position: pos,
    parameters: {
      assignments: { assignments: Object.entries(assignments).map(([k, v]) => ({ id: uuidFrom(name, k), name: k, value: v, type: 'string' })) },
      includeOtherFields: true,
      options: {},
    },
  };
}

function sheetSchema(cols) {
  return cols.map((c) => ({ id: c, displayName: c, required: false, defaultMatch: false, display: true, type: 'string', canBeUsedToMatch: true }));
}

function sheets(name, pos, p, opts = {}) {
  const parameters = {
    operation: p.operation,
    documentId: { __rl: true, mode: 'id', value: p.documentId },
    sheetName: { __rl: true, mode: 'name', value: p.sheetName },
  };
  if (p.operation === 'update' || p.operation === 'appendOrUpdate') {
    const cols = Object.keys(p.values);
    parameters.columns = { mappingMode: 'defineBelow', value: p.values, matchingColumns: [p.matchOn], schema: sheetSchema(cols) };
    parameters.options = {};
  } else {
    parameters.options = {};
  }
  return {
    name,
    type: 'n8n-nodes-base.googleSheets',
    typeVersion: 4.5,
    position: pos,
    parameters,
    credentials: CRED.sheets,
    ...(opts.onError ? { onError: opts.onError } : {}),
    ...(opts.alwaysOutputData ? { alwaysOutputData: true } : {}),
    ...(opts.retry ? { retryOnFail: true, maxTries: 3, waitBetweenTries: 5000 } : {}),
  };
}

function sticky(name, pos, content, width = 420, height = 260) {
  return { name, type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position: pos, parameters: { content, width, height } };
}

